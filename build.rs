//! Build script: generates the embedded emoji table from
//! `assets/emoji/manifest.txt` + the PNG files it names.
//!
//! The manifest is the single source of truth (order = picker order);
//! adding an emoji means dropping `emoji_u<codepoint>.png` in
//! `assets/emoji/` and writing its code point on one manifest line.
//! Std-only, portable paths (`CARGO_MANIFEST_DIR`, forward slashes) —
//! must build on Windows and macOS alike.

use std::{env, fs, path::Path};

fn main() {
    let root = env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR is always set");
    let dir = Path::new(&root).join("assets/emoji");
    let manifest = dir.join("manifest.txt");
    println!("cargo:rerun-if-changed={}", manifest.display());

    let text = fs::read_to_string(&manifest)
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", manifest.display()));

    let mut entries = String::new();
    let mut count = 0u32;
    // The `#` comment nearest above an entry is its group name — the
    // header block is simply overwritten by each later comment.
    let mut last_comment = String::new();
    for (lineno, raw) in text.lines().enumerate() {
        let line = raw.trim();
        if line.is_empty() {
            continue;
        }
        if let Some(c) = line.strip_prefix('#') {
            last_comment = c.trim().to_owned();
            continue;
        }
        let id = u32::from_str_radix(line, 16).unwrap_or_else(|_| {
            panic!(
                "{}:{}: bad emoji id {line:?}",
                manifest.display(),
                lineno + 1
            )
        });
        assert!(
            char::from_u32(id).is_some(),
            "{}:{}: {line} is not a Unicode scalar",
            manifest.display(),
            lineno + 1
        );
        let png = dir.join(format!("emoji_u{line}.png"));
        println!("cargo:rerun-if-changed={}", png.display());
        assert!(
            png.is_file(),
            "{}:{}: missing {}",
            manifest.display(),
            lineno + 1,
            png.display()
        );
        // Literal path for include_bytes! — forward slashes are
        // portable across Windows and Unix toolchains.
        let lit = png.to_string_lossy().replace('\\', "/");
        let section = last_comment.replace('\\', "\\\\").replace('"', "\\\"");
        entries.push_str(&format!(
            "    EmojiDef {{ id: 0x{id:x}, section: \"{section}\", \
             png: include_bytes!(\"{lit}\"), \
             decoded: ::std::sync::OnceLock::new() }},\n"
        ));
        count += 1;
    }
    assert!(count > 0, "{} has no emoji entries", manifest.display());
    // A direct array (not `&[…]`): a static slice of interior-mutable
    // temporaries is rejected (E0492), an inline array is not.
    let out = format!(
        "/// Manifest order — generated by build.rs, do not edit.\n\
         pub(crate) static EMOJI_TABLE: [EmojiDef; {count}] = [\n{entries}];\n"
    );

    let out_dir = env::var("OUT_DIR").expect("OUT_DIR is always set");
    fs::write(Path::new(&out_dir).join("emoji_table.rs"), out)
        .expect("emoji_table.rs must be writable");

    bake_git_hash(&root);
    embed_exe_icon(&root);
}

/// Bakes the short commit into `env!("PIXME_GIT_HASH")` for the startup
/// banner and diagnostics — "unknown" outside a git checkout (a tarball
/// build must not fail over it).
fn bake_git_hash(root: &str) {
    let hash = std::process::Command::new("git")
        .args(["rev-parse", "--short", "HEAD"])
        .current_dir(root)
        .output()
        .ok()
        .filter(|o| o.status.success())
        .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_owned())
        .filter(|v| !v.is_empty())
        .unwrap_or_else(|| "unknown".to_owned());
    println!("cargo:rustc-env=PIXME_GIT_HASH={hash}");
    println!("cargo:rerun-if-changed={root}/.git/HEAD");
}

/// Bakes `assets/app/PixMe.ico` into the Windows executable's resources so
/// the taskbar / Explorer show the PixMe icon. `winresource` is a
/// target-gated build-dependency: it only exists when the build host is
/// Windows, so the real work lives behind `#[cfg(windows)]`.
fn embed_exe_icon(root: &str) {
    println!("cargo:rerun-if-changed={root}/assets/app/PixMe.ico");
    embed_exe_icon_impl();
}

#[cfg(windows)]
fn embed_exe_icon_impl() {
    let mut res = winresource::WindowsResource::new();
    res.set_icon("assets/app/PixMe.ico");
    // VERSIONINFO strings — what Explorer, taskbar tooltips and antivirus
    // heuristics read. Copyright/author strings stay ASCII where the file
    // format allows; these fields are UTF-16 in the PE, so accents are safe.
    res.set("CompanyName", "Frédérik Benoist (dev.q2ii.fr)");
    res.set(
        "FileDescription",
        "PixMe — Screenshot capture and annotation",
    );
    res.set("InternalName", "pixme");
    res.set("LegalCopyright", "© 2026 Frédérik Benoist (dev.q2ii.fr)");
    res.set("OriginalFilename", "pixme.exe");
    res.set("ProductName", "PixMe");
    res.set("Comments", "Licensed under the MIT License");
    res.compile()
        .unwrap_or_else(|e| panic!("cannot embed Windows resources: {e}"));
}

#[cfg(not(windows))]
fn embed_exe_icon_impl() {}
